def ic(name, cls='icon'):
    return f'<svg class="{cls}" aria-hidden="true"><use href="#i-{name}"/></svg>'


def prefix(path):
    """Relative prefix from a page path ('' , 'en/', 'en/services/', 'cgv.html') back to the site root."""
    return '../' * path.split('#')[0].count('/') or ''


